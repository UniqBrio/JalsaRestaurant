#!/usr/bin/env node
/**
 * gen-brand-badge — the bundled Jalsa badge as a TypeScript constant.
 *
 * WHY A CONSTANT AND NOT A FILE READ (26-Sep-2026)
 *   The QR routes put the badge in the middle of every code. Reading it from `public/` at request
 *   time works on a laptop and depends, in a Vercel function, on the build's file tracing having
 *   noticed the read - a quiet failure mode whose only symptom is the drawn "J" coming back. A
 *   constant is in the bundle by construction: there is nothing to trace and nothing to fetch.
 *
 *   The source of truth stays `public/brand/jalsa-badge.png`, which the pages show. This script
 *   derives the constant from it; tests/unit/tables-qr-25sep.unit.spec.ts proves the two agree.
 *
 * Usage:  node scripts/gen-brand-badge.mjs          # write src/lib/brand-badge.generated.ts
 *         node scripts/gen-brand-badge.mjs --check  # exit 1 if the constant is stale
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'public', 'brand', 'jalsa-badge.png');
const target = join(root, 'src', 'lib', 'brand-badge.generated.ts');

const bytes = readFileSync(source);
if (!(bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47)) {
  console.error(`gen-brand-badge: ${source} is not a PNG`);
  process.exit(1);
}
const b64 = bytes.toString('base64');
const lines = b64.match(/.{1,100}/g) ?? [];
const out =
  `/* GENERATED by scripts/gen-brand-badge.mjs from public/brand/jalsa-badge.png - DO NOT EDIT. */\n` +
  `/* Rebuild: npm run badge:build */\n\n` +
  `/** The bundled Jalsa badge, PNG, base64: the logo in the middle of every QR code until one is uploaded. */\n` +
  `export const JALSA_BADGE_PNG_BASE64 =\n` +
  lines.map((l, i) => `  '${l}'${i === lines.length - 1 ? ';' : ' +'}`).join('\n') +
  `\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('gen-brand-badge: src/lib/brand-badge.generated.ts is stale - run npm run badge:build');
    process.exit(1);
  }
  console.log('gen-brand-badge: up to date');
} else {
  writeFileSync(target, out);
  console.log(`gen-brand-badge: wrote ${target} (${bytes.length} bytes)`);
}
