/* --------------------------------------------------------------------------
 * Jalsa service worker.
 *
 * WHAT IT IS FOR, AND WHAT IT DELIBERATELY IS NOT
 *   A guest orders on restaurant wifi from a table in a building with thick walls. The shell
 *   must survive a dead spot; the ORDER must not. So:
 *
 *     - App shell, fonts, icons and static chunks: cache-first, so a dropped signal never
 *       shows a browser error page.
 *     - Anything that reads or writes a bill, a round or a payment: network-only. A cached
 *       bill total is a wrong bill total, and a cached "order placed" is an order the kitchen
 *       never received. Standard 5.7 — degrade honestly rather than pretend.
 *
 *   There is no background sync queue for orders on purpose. Replaying a queued order minutes
 *   later, after the guest has given up and told a captain, is how a table gets its food twice.
 *   The offline state says the round was not sent, and the guest sends it again when the
 *   signal returns.
 * -------------------------------------------------------------------------- */

const VERSION = 'jalsa-v1';
const SHELL = `${VERSION}-shell`;

/* THE FALLBACK IS THE GENERATED STATIC DOCUMENT, NOT THE /offline ROUTE.
 *
 * This used to name '/offline' — the Next route in src/app/offline/page.tsx. That route is a
 * real designed screen and it stays, reachable normally. But as the NO-NETWORK fallback it was
 * wrong twice over. Its HTML links a /_next/static/ stylesheet that this worker precaches
 * nothing of, so a guest whose first trouble is offline gets the page unstyled. And the audit
 * saw the other half: public/offline.html is GENERATED by scripts/theme-build.mjs from
 * design/tokens.json (the `app.offlineFallback` path, default /offline.html) and nothing named
 * it, so the one document built to survive a dead network was never served.
 *
 * The generated file inlines both themes' colours and links no stylesheet and no font, which is
 * the entire reason the framework generates it. Naming it here is what CP-30 and gate G12 mean
 * by "the worker precaches the same path it names".
 */
const OFFLINE_URL = '/offline.html';

/* Precaching the offline page is the whole point of installing: it has to already be on the
 * device at the moment the network is gone.
 *
 * No skipWaiting() here, on purpose (CP-30 rule 4). A worker that takes over on install swaps
 * the code under a session already in progress — the round a guest is part-way through
 * composing. The new version waits; the page offers it; the guest decides. The only path to
 * skipWaiting is the message handler at the bottom of this file. */
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL)
      .then((cache) => cache.addAll([OFFLINE_URL, '/manifest.webmanifest', '/brand/icon-192.png']))
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => !k.startsWith(VERSION)).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

/** Everything that touches money, an order or a session. Never cached, never replayed. */
const isLiveData = (url) =>
  url.pathname.startsWith('/api/') ||
  url.pathname.startsWith('/auth/') ||
  url.hostname.endsWith('.supabase.co');

const isStaticAsset = (url) =>
  url.origin === self.location.origin &&
  (url.pathname.startsWith('/_next/static/') ||
    url.pathname.startsWith('/brand/') ||
    url.pathname === '/manifest.webmanifest');

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (isLiveData(url)) return; // straight to the network; a failure surfaces as a failure

  if (isStaticAsset(url)) {
    event.respondWith(
      caches.match(request).then(
        (hit) =>
          hit ??
          fetch(request).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(SHELL).then((c) => c.put(request, copy));
            }
            return res;
          })
      )
    );
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(OFFLINE_URL).then((hit) => hit ?? Response.error())
      )
    );
  }
});

/**
 * The guest accepted the update. This is the ONLY path to skipWaiting, and it is a response to
 * an explicit tap made while the page that will reload is still on screen — never a decision
 * this worker takes for them. CP-30 rule 4: offered, never imposed.
 */
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});
