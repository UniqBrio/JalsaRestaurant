/* ── Items 4, 5: the bill's structure and alignment ────────────────────── */

for (const width of ['58', '80'] as PaperWidth[]) {
  test(`items 4-5: ${width} mm - every figure column ends at the paper's edge, under its heading`, () => {
    const cols = PAPER[width].cols.normal;
    const lines = invoiceLines(BILL, WHO, width, undefined);
    const plain = lines.filter((l) => l.weight !== 'big');
    // Nothing is wider than the roll; nothing big is wider than half of it.
    for (const l of lines) expect(l.text.length, l.text).toBeLessThanOrEqual(l.weight === 'big' ? bigColsFor(cols) : cols);
    const header = plain.find((l) => l.text.startsWith('ITEM'));
    expect(header?.weight).toBe('bold');
    expect(header?.text.length).toBe(cols);
    expect(header?.text.endsWith('AMOUNT')).toBe(true);
    expect(header?.text).toContain('QTY');
    expect(header?.text).toContain('RATE');
    // Every item row: its amount ends at the last column, its qty ends where QTY ends.
    const qtyEnd = (header?.text.indexOf('QTY') ?? 0) + 3;
    for (const name of ['Paneer', 'Butter Naan', 'Chicken 65', 'Egg Curry', 'Gulab Jamun']) {
      const row = plain.find((l) => l.text.startsWith(name.slice(0, 6)) && /\d$/.test(l.text));
      expect(row, name).toBeTruthy();
      expect(row!.text.length, name).toBe(cols);
      expect(row!.text[qtyEnd - 1], `${name}: qty right-aligned under QTY`).toMatch(/\d/);
    }
    const naan = plain.find((l) => l.text.startsWith('Butter Naan'))!.text;
    expect(naan.endsWith('540')).toBe(true);
    // Totals: labels left, figures right, at the same edge.
    for (const label of ['SUBTOTAL', 'DISCOUNT', 'CGST', 'SGST']) {
      const row = plain.find((l) => l.text.startsWith(label));
      expect(row, label).toBeTruthy();
      expect(row!.text.length, label).toBe(cols);
    }
    const total = lines.find((l) => l.text.startsWith('TOTAL'));
    expect(total?.weight).toBe('big');
    expect(total?.text.length).toBe(bigColsFor(cols));
  });
}

