test('item 9: the bill preview is byte-for-byte what composeTicket prints for that bill at that width', () => {
  const template: Partial<TemplateConfig> = { separator: 'equals' };
  for (const width of ['58', '80'] as PaperWidth[]) {
    const now = new Date('2026-09-24T15:00:00Z');
    const preview = ticketPreview({ kind: 'bill', width, template, menu: [], who: WHO, taxRate: 5, bill: BILL, now });
    const { items, totals, upiId, station: _s, ...header } = invoiceTicketData(BILL, WHO, now);
    void _s;
    void upiId;
    const printed = composeTicket({
      job: { id: 'j', kind: 'bill', printerId: 'c', station: 'Billing', foodSide: 'all', isReprint: false },
      width,
      template,
      printers: [],
      splitByFoodType: false,
      header,
      items,
      ...(totals ? { totals } : {}),
    });
    if (!printed.ok) throw new Error(printed.blocked);
    expect(hex(encodeTicket(preview.lines, { ...DEFAULT_ENCODER, width }))).toBe(hex(encodeTicket(printed.lines, { ...DEFAULT_ENCODER, width })));
    expect(preview.cols).toBe(PAPER[width].cols.normal);
  }
});

