/* ── Item 7: the printable width, no left margin ───────────────────────── */

test('item 7: with area on, the encoder sets left margin 0 and the full printable width, then the font', () => {
  const lines = [{ text: 'X', weight: 'plain' as const }];
  const h80 = hex(encodeTicket(lines, { ...DEFAULT_ENCODER, width: '80', area: true }));
  expect(h80.startsWith('1B 40 1B 74 00 1D 4C 00 00 1D 57 40 02 1B 4D 00')).toBe(true); // 576 dots
  const h58 = hex(encodeTicket(lines, { ...DEFAULT_ENCODER, width: '58', area: true, font: 'small' }));
  expect(h58.startsWith('1B 40 1B 74 00 1D 4C 00 00 1D 57 80 01 1B 4D 01')).toBe(true); // 384 dots, font B
  // Off by default: every pinned golden keeps its bytes.
  expect(hex(encodeTicket(lines, DEFAULT_ENCODER)).startsWith('1B 40 1B 74 00 58')).toBe(true);
});

