#!/usr/bin/env node
/**
 * check-column-control - a table wide enough to scroll must let the user choose its columns.
 *
 * THE DEFECT THIS FINDS
 *   Past three or four columns a table stops fitting and starts scrolling sideways, so most of
 *   it is off screen at any moment. Which columns matter is a property of the TASK, not of the
 *   table, so a fixed layout guesses wrong for everyone and the columns someone actually needs
 *   are the ones they scroll to every single time.
 *
 *   The reason this needs a gate rather than good intentions: the table is fine on the developer's
 *   monitor with four columns of seed data. It becomes unusable later, one column at a time, and
 *   no single change is ever the one that broke it.
 *
 * THE RULE
 *   More than THRESHOLD columns -> the screen offers a column control (choose, reorder, reset),
 *   and the preference persists. Canonical pattern CP-21; reference `src/components/ColumnControl.tsx`.
 *
 * WHAT THIS GATE CANNOT SEE (state the limit; never imply more)
 *   It counts LITERAL `<th>` elements. A table whose columns are generated by mapping over a
 *   definition array is invisible to it, and so is one rendered by a shared DataTable component.
 *   Those are not decidable syntactically, and a detector that is confidently wrong is worse
 *   than one that declines. This is a FLOOR: the review checklist carries the rest, and says so.
 *
 * USAGE
 *   node scripts/audits/check-column-control.mjs [--dir <src>] [--threshold 3] [--report|--write-baseline]
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { evaluateRatchet, writeBaseline, walk } from '../lib/ratchet.mjs';
import { appPath } from '../lib/layout.mjs';

const argv = process.argv.slice(2);
const arg = (n, d) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const ROOT = process.cwd();
const DIR = path.resolve(ROOT, arg('--dir', appPath(ROOT, 'src')));
const BASELINE = path.resolve(ROOT, arg('--baseline', appPath(ROOT, '.baselines/column-control-baseline.txt')));
const THRESHOLD = Number(arg('--threshold', '3'));
const CMD = 'node scripts/audits/check-column-control.mjs --write-baseline';

/* A header cell, opening tag only. `<thead>` must not match, hence the boundary. */
const TH_OPEN = /<th[\s/>]/g;

/**
 * Evidence that this screen already offers the control. Deliberately a SET OF MARKERS rather
 * than one blessed import: an app may legitimately name its own wrapper, and a gate that only
 * accepts one spelling gets worked around instead of satisfied. Each marker is something that
 * cannot appear by accident.
 */
const CONTROL_MARKERS = [
  /ColumnControl/,
  /useColumnPrefs/,
  /columnPrefs/i,
  /data-testid\s*=\s*[`"'{][^`"'}]*-columns\b/,
];

const files = walk(DIR, { exts: ['.tsx', '.jsx'] }).filter((f) => !/\.(test|spec)\./.test(f));

const signatures = [];
let widestSeen = 0;
let tablesSeen = 0;
for (const file of files) {
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  const src = fs.readFileSync(file, 'utf8');
  const columns = (src.match(TH_OPEN) ?? []).length;
  if (columns === 0) continue;
  tablesSeen++;
  widestSeen = Math.max(widestSeen, columns);
  if (columns <= THRESHOLD) continue;
  if (CONTROL_MARKERS.some((re) => re.test(src))) continue;
  signatures.push(`${rel}|${columns}`);
}

if (argv.includes('--report')) {
  signatures.length
    ? signatures.forEach((s) => console.log(`NO COLUMN CONTROL  ${s}`))
    : console.log('Every literal table wider than the threshold offers a column control.');
  console.log(`\n${files.length} file(s) scanned, ${tablesSeen} with a literal table, widest ${widestSeen} column(s).`);
  console.log(`Threshold: more than ${THRESHOLD} columns. Dynamically built tables are NOT visible here - see the review checklist.`);
  process.exit(0);
}

if (argv.includes('--write-baseline')) {
  const n = writeBaseline(BASELINE, signatures, {
    name: 'COLUMN CONTROL',
    regenerateCmd: CMD,
    note: `Signature: <path>|<column count>. A table wider than ${THRESHOLD} columns with no column control (CP-21).`,
  });
  console.log(`wrote ${path.relative(ROOT, BASELINE)} (${n} table(s) without a column control)`);
  process.exit(0);
}

process.exit(
  evaluateRatchet({
    name: 'COLUMN CONTROL',
    signatures,
    baselineFile: BASELINE,
    regenerateCmd: CMD,
    // Zero .tsx/.jsx files means the scan read nothing - which looks exactly like a clean tree.
    parsedSomething: files.length > 0,
    remediation:
      'Give the table a column control: choose, reorder, reset, and remember the choice (CP-21).\n' +
      '  Reference: src/components/ColumnControl.tsx + src/hooks/useColumnPrefs.ts.\n' +
      '  A column the table is unreadable without is marked `required` - reorderable, never hideable.',
  })
);
